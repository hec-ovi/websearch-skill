class SearxngRequest(BaseModel):
    """Mirrors contracts/searxng.schema.json#/$defs/SearxngRequest."""

    model_config = ConfigDict(extra="forbid")

    action: Literal["up", "status", "down"]
    reinstall: bool = False
    ref: str | None = None


class SearxngPayload(BaseModel):
    """Mirrors contracts/searxng.schema.json#/$defs/SearxngPayload."""

    model_config = ConfigDict(extra="forbid")

    action: Literal["up", "status", "down"]
    home: str
    url: str
    installed: bool
    pid: int | None = None
    healthy: bool
    egress: str | None = None
    wired: str | None = None
    version: str | None = None
    engines_active: int | None = Field(default=None, ge=0)
    engines_available: int | None = Field(default=None, ge=0)
    log: str | None = None


def _payload(action: str, paths: Paths, p: int, *, wired: Path | None) -> SearxngPayload:
    state = status(paths, p)
    return SearxngPayload(
        action=action,  # type: ignore[arg-type]
        home=state["home"],
        url=state["url"],
        installed=state["installed"],
        pid=state["pid"],
        healthy=state["healthy"],
        egress=state["egress"],
        wired=str(wired) if wired else None,
        version=state.get("version"),
        engines_active=state.get("engines_active"),
        engines_available=state.get("engines_available"),
        log=state["log"],
    )


def refresh_if_running() -> str | None:
    """Restart a running instance whose settings no longer match the egress. Returns its
    URL when it was restarted, else None.

    Settings are read once at startup, so an instance started before the exit changed
    keeps using the old one: the searches would still come from the previous city while
    everything else moved. Called by the commands that change the egress.
    """
    try:
        p = port()
    except SearxngError:
        return None
    paths = Paths(home_dir())
    url = base_url(p)
    if running_pid(paths) is None or not is_healthy(url):
        return None
    tor_socks = _tor_socks()
    proxy = outgoing_proxy()
    if not settings_stale(paths, p, tor_socks, proxy):
        return None
    write_settings(paths, p, tor_socks=tor_socks, proxy=proxy)
    stop(paths)
    start(paths, p)
    return url if wait_healthy(url) else None


def _error(code: str, message: str, *, retriable: bool) -> Envelope:
    return error_envelope(
        SEARXNG_CONTRACT_VERSION,
        code=code,
        message=message,
        retriable=retriable,
        layer="searxng",
        backend="searxng-local",
    )


def control(request: SearxngRequest) -> Envelope:
    """Run one lifecycle action and describe the resulting state.

    The single entry point behind both the ``searxng`` CLI command and the
    ``searxng_setup`` MCP tool, so the two faces cannot drift.
    """
    started = time.monotonic()
    try:
        p = port()
    except SearxngError as exc:
        return _error(errors.INVALID_REQUEST, str(exc), retriable=False)
    paths = Paths(home_dir())
    url = base_url(p)

    if request.action == "status":
        return _ok(_payload("status", paths, p, wired=None), started)

    if request.action == "down":
        stop(paths)
        return _ok(_payload("down", paths, p, wired=None), started)

    tor_socks = _tor_socks()
    try:
        proxy = outgoing_proxy()
    except ProxyConfigError as exc:
        return _error(errors.INVALID_REQUEST, str(exc), retriable=False)
    if is_healthy(url):
        # Never install over something that is already answering. It may still need a
        # restart: an instance started before the egress changed still uses the old one,
        # and settings are only read at startup.
        if settings_stale(paths, p, tor_socks, proxy) and running_pid(paths) is not None:
            write_settings(paths, p, tor_socks=tor_socks, proxy=proxy)
            stop(paths)
            start(paths, p)
            if not wait_healthy(url):
                return _error(
                    errors.UPSTREAM_ERROR,
                    f"SearXNG did not come back after a settings change; its log is at {paths.log}",
                    retriable=True,
                )
        return _ok(_payload("up", paths, p, wired=wire_env_file(url)), started)
    try:
        if request.reinstall or not paths.granian.exists():
            install(paths, ref=request.ref, reinstall=request.reinstall)
        write_settings(paths, p, tor_socks=tor_socks, proxy=proxy)
        start(paths, p)
    except SearxngError as exc:
        return _error(errors.DEPENDENCY_MISSING, str(exc), retriable=False)
    if not wait_healthy(url):
        stop(paths)
        return _error(
            errors.UPSTREAM_ERROR,
            f"SearXNG did not answer at {url} within {HEALTH_TIMEOUT_S}s; its log is at "
            f"{paths.log}",
            retriable=True,
        )
    return _ok(_payload("up", paths, p, wired=wire_env_file(url)), started)


def _ok(payload: SearxngPayload, started: float) -> Envelope:
    return ok_envelope(
        SEARXNG_CONTRACT_VERSION,
        payload.model_dump(mode="json"),
        layer="searxng",
        backend="searxng-local",
        elapsed_ms=round((time.monotonic() - started) * 1000, 3),
    )
